// Difference bewteen Encoding, Encryption and Hashing


// Encoding
/**
 * PURPOSE - to represent data in a different format
 * EXAMPLES - Base64, URL Encoding, Hexadecimal, etc.
 * Key/SECRETRequired: NO 
 * REVERSIBLE: YES
 * SECURITY: LOW/NONE 
 */


// HASHING 
/**
 * PURPOSE - to convert data into a fixed-length string of characters
 * EXAMPLES - MD5, SHA-1, SHA-256, SHA-512, etc.
 * Key/SECRETRequired: NO
 * REVERSIBLE: NO
 * SECURITY: HIGH
 * 
 * 
 * MD5: dead security.
 * sha1- is dying, google collision demonstration
 * */

// ENCRYPTION
/**
 * PURPOSE - to convert data into a different format that is not easily reversible
 * EXAMPLES - AES, RSA, etc.
 * Key/SECRETRequired: YES
 * REVERSIBLE: YES (with the correct key)
 * SECURITY: MEDIUM
 * 
 * */

